/**
 * One hermetic egirl instance: its own temp root, HOME, workspace and config, run as
 * `egirl api` against the recording proxy.
 *
 * Nothing of the real machine reaches it. HOME is the temp root's home/, so ~/.egirl,
 * ~/.config/gh, ~/.ssh and ~/.codex resolve inside it; EGIRL_CONFIG names the generated config
 * so the repo's egirl.toml and ~/Projects/egirl-run/egirl.d are never looked at (fragments are
 * read only beside the config file in use); the environment is built from an allowlist, so no
 * GH_TOKEN, GITHUB_TOKEN, ANTHROPIC_API_KEY, SSH_AUTH_SOCK or EGIRL_* from the caller's shell;
 * and the process runs from the temp root with --no-env-file, so Bun loads no .env.
 */

import { type ChildProcess, spawn } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { stringify } from 'smol-toml'
import type { TomlTable } from './types'

const ROOT = join(import.meta.dir, '..', '..')

export interface InstancePaths {
  root: string
  home: string
  workspace: string
  configPath: string
}

export function makePaths(root: string): InstancePaths {
  const home = join(root, 'home')
  const workspace = join(root, 'workspace')
  mkdirSync(home, { recursive: true })
  mkdirSync(workspace, { recursive: true })
  return { root, home, workspace, configPath: join(root, 'egirl.toml') }
}

function isTable(v: unknown): v is TomlTable {
  return typeof v === 'object' && v !== null && !Array.isArray(v)
}

export function deepMerge(base: TomlTable, over: TomlTable): TomlTable {
  const out: TomlTable = { ...base }
  for (const [k, v] of Object.entries(over)) {
    const cur = out[k]
    out[k] = isTable(cur) && isTable(v) ? deepMerge(cur, v) : v
  }
  return out
}

