export function writeConfig(paths: InstancePaths, config: TomlTable): void {
  writeFileSync(paths.configPath, `# generated by bench/scenarios/run.ts\n${stringify(config)}\n`)
}

/** The whole environment the instance sees. Allowlisted, not filtered. */
export function instanceEnv(
  paths: InstancePaths,
  endpoint: string,
  model: string,
): Record<string, string> {
  const pass = ['PATH', 'LANG', 'LC_ALL', 'TZ', 'TERM']
  const env: Record<string, string> = {}
  for (const k of pass) {
    const v = process.env[k]
    if (v !== undefined) env[k] = v
  }
  return {
    ...env,
    HOME: paths.home,
    XDG_CONFIG_HOME: join(paths.home, '.config'),
    XDG_DATA_HOME: join(paths.home, '.local', 'share'),
    XDG_CACHE_HOME: join(paths.home, '.cache'),
    TMPDIR: join(paths.root, 'tmp'),
    EGIRL_CONFIG: paths.configPath,
    EGIRL_LOCAL_ENDPOINT: endpoint,
    EGIRL_LOCAL_MODEL: model,
    EGIRL_LOCAL_TEMPERATURE: '0',
    NO_COLOR: '1',
  }
}

export interface Instance {
  url: string
  stderrTail(): string
  stop(): Promise<void>
}

export async function freePort(): Promise<number> {
  const s = Bun.serve({ hostname: '127.0.0.1', port: 0, fetch: () => new Response() })
  const port = s.port ?? 0
  s.stop(true)
  return port
}

export async function startInstance(
  paths: InstancePaths,
  apiPort: number,
  env: Record<string, string>,
  bootMs = 60_000,
): Promise<Instance> {
  mkdirSync(env.TMPDIR as string, { recursive: true })
  const child: ChildProcess = spawn(
    'bun',
    ['--no-env-file', join(ROOT, 'src', 'index.ts'), 'api'],
    { cwd: paths.root, env, stdio: ['ignore', 'pipe', 'pipe'] },
  )
  let tail = ''
  const keep = (d: Buffer) => {
    tail = (tail + d.toString()).slice(-4000)
  }
  child.stdout?.on('data', keep)
  child.stderr?.on('data', keep)
  let exited: number | null | undefined
  child.on('exit', (code) => {
    exited = code
  })

  const stop = async (): Promise<void> => {
    if (exited !== undefined) return
    child.kill('SIGTERM')
    const gone = await Promise.race([
      new Promise<boolean>((r) => child.once('exit', () => r(true))),
      Bun.sleep(5000).then(() => false),
    ])
    if (!gone) child.kill('SIGKILL')
  }

  const url = `http://127.0.0.1:${apiPort}`
  const deadline = Date.now() + bootMs
  while (Date.now() < deadline) {
    if (exited !== undefined) {
      throw new Error(`egirl exited during boot (code ${exited}):\n${tail}`)
    }
    try {
      const res = await fetch(`${url}/`, { signal: AbortSignal.timeout(1000) })
      if (res.ok) return { url, stderrTail: () => tail, stop }
    } catch {
      // not listening yet
    }
    await Bun.sleep(250)
  }
  await stop()
  throw new Error(`egirl not healthy after ${bootMs / 1000}s:\n${tail}`)
}
